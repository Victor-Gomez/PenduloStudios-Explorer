        hotspotY = DefaultHotspotY;

        if (dibData.Length < 40)
            throw new ArgumentException($"DIB data too short ({dibData.Length} bytes).", nameof(dibData));

        // Check if preceded by a 4-byte cursor hotspot header
        if (BinaryPrimitives.ReadInt32LittleEndian(dibData) != 40
            && dibData.Length >= 44
            && BinaryPrimitives.ReadInt32LittleEndian(dibData.Slice(4)) == 40)
        {
            hotspotX = BinaryPrimitives.ReadUInt16LittleEndian(dibData);
            hotspotY = BinaryPrimitives.ReadUInt16LittleEndian(dibData.Slice(2));
            dibData = dibData.Slice(4);
        }

        int biSize = BinaryPrimitives.ReadInt32LittleEndian(dibData);
        if (biSize != 40)
            throw new NotSupportedException($"Only standard 40-byte BITMAPINFOHEADER is supported (got {biSize}).");

        int width = BinaryPrimitives.ReadInt32LittleEndian(dibData.Slice(4));
        int biHeight = BinaryPrimitives.ReadInt32LittleEndian(dibData.Slice(8));
        int height = biHeight / 2; // Icon/cursor DIBs include both XOR and AND masks in declared height
        short planes = BinaryPrimitives.ReadInt16LittleEndian(dibData.Slice(12));
        short bitCount = BinaryPrimitives.ReadInt16LittleEndian(dibData.Slice(14));

        if (width <= 0 || height <= 0 || bitCount != 1)
            throw new NotSupportedException($"Unsupported cursor dimensions/depth ({width}×{height}, {bitCount} bpp).");

        int pitch = ((width * bitCount + 31) / 32) * 4;
        int maskBytes = height * pitch;
        int colorTableSize = 2 * 4; // 2 RGBQUAD entries
        int xorOffset = biSize + colorTableSize;
        int andOffset = xorOffset + maskBytes;

        if (dibData.Length < andOffset + maskBytes)
            throw new ArgumentException($"DIB data truncated: expected at least {andOffset + maskBytes} bytes, got {dibData.Length}.");

        ReadOnlySpan<byte> xorMask = dibData.Slice(xorOffset, maskBytes);
        ReadOnlySpan<byte> andMask = dibData.Slice(andOffset, maskBytes);

        var bgra = new byte[width * height * 4];

        // Windows DIB scanlines are bottom-up: scanline 0 is the bottom row
        for (int y = 0; y < height; y++)
        {
            int srcRow = height - 1 - y;
            int srcRowOffset = srcRow * pitch;

            for (int x = 0; x < width; x++)
            {
                int byteIdx = srcRowOffset + (x / 8);
                int bitShift = 7 - (x % 8);
                int xorBit = (xorMask[byteIdx] >> bitShift) & 1;
                int andBit = (andMask[byteIdx] >> bitShift) & 1;

                int dstIdx = (y * width + x) * 4;

                if (andBit == 1 && xorBit == 0)
                {
                    // Transparent
                    bgra[dstIdx] = 0;
                    bgra[dstIdx + 1] = 0;
                    bgra[dstIdx + 2] = 0;
                    bgra[dstIdx + 3] = 0;
                }
                else if (andBit == 0)
                {
                    // Opaque: 0 = Black, 1 = White
                    byte color = (byte)(xorBit == 1 ? 255 : 0);
                    bgra[dstIdx] = color;
                    bgra[dstIdx + 1] = color;
                    bgra[dstIdx + 2] = color;
                    bgra[dstIdx + 3] = 255;
                }
                else
                {
                    // Invert (AND=1, XOR=1) -> render as white in standard viewers
                    bgra[dstIdx] = 255;
                    bgra[dstIdx + 1] = 255;
                    bgra[dstIdx + 2] = 255;
                    bgra[dstIdx + 3] = 255;
                }
            }
        }

        return new DecodedImage(width, height, bgra);
    }

    /// <summary>Creates the animated cursor asset using the 6 fallback DIBs.</summary>
    public static HollywoodCursorAsset CreateFallbackAsset()
    {
        var frames = new DecodedImage[UniqueFrameCount];
        for (int i = 0; i < UniqueFrameCount; i++)
        {
            frames[i] = DecodeDib(FallbackDibs[i], out _, out _);
        }
        return new HollywoodCursorAsset(frames, DefaultHotspotX, DefaultHotspotY);
    }
}

/// <summary>
/// Hollywood Monsters animated cursor asset implementing <see cref="IAnimationAsset"/>.
/// Consists of 10 playback frames cycling across the 6 unique cursor frames.
/// </summary>
public sealed class HollywoodCursorAsset : IAnimationAsset
{
    private readonly DecodedImage[] _uniqueFrames;

    public HollywoodCursorAsset(DecodedImage[] uniqueFrames, int hotspotX, int hotspotY)
    {
        ArgumentNullException.ThrowIfNull(uniqueFrames);
        if (uniqueFrames.Length != HollywoodCursorDecoder.UniqueFrameCount)
            throw new ArgumentException($"Expected {HollywoodCursorDecoder.UniqueFrameCount} unique frames, got {uniqueFrames.Length}.");

        _uniqueFrames = uniqueFrames;
        HotspotX = hotspotX;
        HotspotY = hotspotY;
    }

    public int FrameCount => HollywoodCursorDecoder.AnimationFrameCount;

    public (int X, int Y, int Width, int Height) Bounds =>
        (0, 0, HollywoodCursorDecoder.CursorWidth, HollywoodCursorDecoder.CursorHeight);

    public int HotspotX { get; }
    public int HotspotY { get; }

    public SpriteFrame DecodeFrame(int index)
    {
        if (index < 0 || index >= FrameCount)
            throw new ArgumentOutOfRangeException(nameof(index));

        int uniqueIndex = HollywoodCursorDecoder.FrameSequence[index];
        return new SpriteFrame(_uniqueFrames[uniqueIndex], 0, 0);
    }

    public string? Verify() => null;
}
